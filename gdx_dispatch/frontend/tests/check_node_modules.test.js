// @vitest-environment node
/**
 * Negative tests for scripts/check_node_modules.mjs (GDXA-523). Each case
 * builds a throwaway frontend dir with a lockfile and a fake node_modules,
 * runs the real script on it as `pretest` would, and asserts it fails on
 * drift and passes on a faithful install. Without these, a broken comparison
 * would turn the pretest hook into a no-op that always says "fine".
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { afterEach, describe, expect, it } from 'vitest';

const SCRIPT = fileURLToPath(new URL('../scripts/check_node_modules.mjs', import.meta.url));

const dirs = [];
afterEach(() => {
  while (dirs.length) fs.rmSync(dirs.pop(), { recursive: true, force: true });
});

function fixture({ locked, installed, hidden, noModules = false }) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'check-node-modules-'));
  dirs.push(root);
  const packages = { '': { name: 'fixture' } };
  for (const [name, entry] of Object.entries(locked)) packages[`node_modules/${name}`] = entry;
  fs.writeFileSync(
    path.join(root, 'package-lock.json'),
    JSON.stringify({ lockfileVersion: 3, packages }),
  );
  if (noModules) return root;
  fs.mkdirSync(path.join(root, 'node_modules'));
  for (const [name, version] of Object.entries(installed)) {
    const dir = path.join(root, 'node_modules', name);
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, 'package.json'), JSON.stringify({ name, version }));
  }
  if (hidden) {
    const hiddenPackages = {};
    for (const name of hidden) hiddenPackages[`node_modules/${name}`] = {};
    fs.writeFileSync(
      path.join(root, 'node_modules', '.package-lock.json'),
      JSON.stringify({ lockfileVersion: 3, packages: hiddenPackages }),
    );
  }
  return root;
}

function run(root) {
  try {
    execFileSync(process.execPath, [SCRIPT, root], { encoding: 'utf8', stdio: 'pipe' });
    return { code: 0, out: '' };
  } catch (e) {
    return { code: e.status, out: `${e.stdout || ''}${e.stderr || ''}` };
  }
}

describe('check_node_modules.mjs', () => {
  it('passes when every locked package is installed at its locked version', () => {
    const root = fixture({
      locked: { vue: { version: '3.5.43' }, 'vue/node_modules/semver': { version: '7.0.0' } },
      installed: { vue: '3.5.43', 'vue/node_modules/semver': '7.0.0' },
      hidden: ['vue', 'vue/node_modules/semver'],
    });
    expect(run(root)).toEqual({ code: 0, out: '' });
  });

  it('fails naming a package installed at a different version than the lock', () => {
    const root = fixture({
      locked: { vue: { version: '3.5.43' } },
      installed: { vue: '3.5.32' },
    });
    const { code, out } = run(root);
    expect(code).toBe(1);
    expect(out).toContain('vue 3.5.32 (lock: 3.5.43)');
    expect(out).toContain('npm ci');
  });

  it('fails naming a locked package that is not installed', () => {
    const root = fixture({
      locked: { vue: { version: '3.5.43' }, dompurify: { version: '3.4.16' } },
      installed: { vue: '3.5.43' },
    });
    const { code, out } = run(root);
    expect(code).toBe(1);
    expect(out).toMatch(/not installed:\s+dompurify/);
  });

  it('fails naming an installed package the lock no longer lists', () => {
    const root = fixture({
      locked: { vue: { version: '3.5.43' } },
      installed: { vue: '3.5.43', 'left-pad': '1.3.0' },
      hidden: ['vue', 'left-pad'],
    });
    const { code, out } = run(root);
    expect(code).toBe(1);
    expect(out).toMatch(/not in package-lock\.json:\s+left-pad/);
  });

  it('fails when node_modules is missing altogether', () => {
    const root = fixture({ locked: { vue: { version: '3.5.43' } }, noModules: true });
    const { code, out } = run(root);
    expect(code).toBe(1);
    expect(out).toContain('node_modules is missing');
  });

  it('tolerates an absent optional package or one built for another platform', () => {
    const otherOs = process.platform === 'win32' ? 'linux' : 'win32';
    const root = fixture({
      locked: {
        vue: { version: '3.5.43' },
        fsevents: { version: '2.3.3', optional: true },
        '@esbuild/other': { version: '0.25.0', dev: true, os: [otherOs] },
      },
      installed: { vue: '3.5.43' },
    });
    expect(run(root)).toEqual({ code: 0, out: '' });
  });

  it('still fails on a platform package built for THIS platform when it is absent', () => {
    const root = fixture({
      locked: {
        vue: { version: '3.5.43' },
        '@esbuild/here': { version: '0.25.0', dev: true, os: [process.platform] },
      },
      installed: { vue: '3.5.43' },
    });
    const { code, out } = run(root);
    expect(code).toBe(1);
    expect(out).toContain('@esbuild/here');
  });
});
