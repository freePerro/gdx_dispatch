#!/usr/bin/env node
/**
 * Refuse to run against a node_modules that does not match package-lock.json.
 *
 * `npm ci` runs only in CI and the Docker build. A local install drifts the
 * moment the lockfile moves on main and nobody reinstalls, and vitest then
 * passes or fails against packages CI never sees (GDXA-523: vue 3.5.32
 * installed while the lock pinned 3.5.43). Worktrees share one node_modules
 * by symlink, so this script only REPORTS — it never installs.
 *
 * Wired as `pretest`, `predev` and `prebuild`. A bare `npx vitest run`
 * skips npm lifecycle scripts and so skips this check; run
 * `node scripts/check_node_modules.mjs` by hand before one.
 *
 * Usage: node scripts/check_node_modules.mjs [frontend-dir]
 * Exit 0 when every package the lock lists is installed at the locked
 * version and nothing else is; exit 1 otherwise, naming the packages.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SHOW = 10;

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

// npm skips a package whose os/cpu/libc fields exclude this platform, so its
// absence is not drift. Same "!value" negation syntax as npm.
function excludedHere(list, current) {
  if (!Array.isArray(list) || list.length === 0 || current == null) return false;
  if (list.includes(`!${current}`)) return true;
  const positive = list.filter((v) => !v.startsWith('!'));
  return positive.length > 0 && !positive.includes(current);
}

function libcHere() {
  if (process.platform !== 'linux') return null;
  const header = process.report?.getReport?.().header;
  return header?.glibcVersionRuntime ? 'glibc' : 'musl';
}

function skippableWhenMissing(entry) {
  if (entry.optional) return true;
  return (
    excludedHere(entry.os, process.platform) ||
    excludedHere(entry.cpu, process.arch) ||
    (entry.libc ? excludedHere(entry.libc, libcHere()) : false)
  );
}

function checkNodeModules(root) {
  const lockFile = path.join(root, 'package-lock.json');
  const modules = path.join(root, 'node_modules');
  if (!fs.existsSync(lockFile)) return { problems: [`no package-lock.json in ${root}`] };
  if (!fs.existsSync(modules)) return { problems: ['node_modules is missing'] };

  const locked = readJson(lockFile).packages || {};
  const wrong = [];
  const missing = [];
  for (const [key, entry] of Object.entries(locked)) {
    if (!key.startsWith('node_modules/') || entry.link) continue;
    const pkgJson = path.join(root, key, 'package.json');
    if (!fs.existsSync(pkgJson)) {
      if (!skippableWhenMissing(entry)) missing.push(key.slice('node_modules/'.length));
      continue;
    }
    const installed = readJson(pkgJson).version;
    if (entry.version && installed !== entry.version) {
      wrong.push(`${key.slice('node_modules/'.length)} ${installed} (lock: ${entry.version})`);
    }
  }

  // npm's hidden lockfile records what the last install put on disk; anything
  // there the lock no longer lists is left over from an older lock.
  const extraneous = [];
  const hidden = path.join(modules, '.package-lock.json');
  if (fs.existsSync(hidden)) {
    for (const key of Object.keys(readJson(hidden).packages || {})) {
      if (key.startsWith('node_modules/') && !(key in locked)) {
        extraneous.push(key.slice('node_modules/'.length));
      }
    }
  }

  const problems = [];
  const section = (label, items) => {
    if (items.length === 0) return;
    problems.push(`${items.length} ${label}:`);
    for (const item of items.slice(0, SHOW)) problems.push(`  ${item}`);
    if (items.length > SHOW) problems.push(`  ... and ${items.length - SHOW} more`);
  };
  section('installed at a different version than package-lock.json', wrong);
  section('in package-lock.json but not installed', missing);
  section('installed but not in package-lock.json', extraneous);
  return { problems };
}

const ROOT = path.resolve(
  process.argv[2] || path.join(path.dirname(fileURLToPath(import.meta.url)), '..'),
);
{
  const { problems } = checkNodeModules(ROOT);
  if (problems.length > 0) {
    console.error(`node_modules does not match package-lock.json (${ROOT}):`);
    for (const line of problems) console.error(`  ${line}`);
    console.error('Run `npm ci` in gdx_dispatch/frontend, then retry.');
    console.error(
      'In a Paperclip worktree node_modules is a symlink to the main checkout: ' +
        'reinstall there, not here.',
    );
    process.exit(1);
  }
}
