# ── regressions found by the pre-commit adversarial audit ────────────────────


def test_publish_is_not_reachable_through_a_nav_key():
    """The publish boundary must not rest on a nav-visibility key.

    The first implementation gated approval on `inventory.write` + `nav.office`.
    Both are things an admin edits in the Roles UI, and `core/permissions.py`
    documents nav.* as "nav-visibility ONLY (no API route enforces these)" — so
    giving technicians office navigation, a change that looks purely cosmetic,
    silently handed them the ability to publish to the public internet.

    This pins the shape of the fix, not just one role's current perm list.
    """
    from gdx_dispatch.core.permissions import BUILTIN_ROLES, WILDCARD

    tech = BUILTIN_ROLES["technician"]
    assert "listings.publish" not in tech
    # ...and it must not be reachable by adding office nav to that role.
    assert "listings.publish" not in set(tech) | {"nav.office", "nav.admin"}

    # admin/owner resolve against live BUILTIN_ROLES, so they need no backfill.
    assert "listings.publish" in BUILTIN_ROLES["admin"]
    assert WILDCARD in BUILTIN_ROLES["owner"]

    # No other builtin role gets it implicitly — fail-closed by default.
    for role in ("dispatcher", "sales", "accounting", "viewer"):
        assert "listings.publish" not in BUILTIN_ROLES[role], role


def test_patch_does_not_wipe_fields_the_client_did_not_send(office: TestClient):
    """A one-word title fix must not blank the rest of the row.

    `_apply` used to setattr every field from the payload's defaults, so a PATCH
    carrying only {title} reset brand, model, material, R-value and qty — data a
    portal customer may have typed.
    """
    listing = _create(
        office, title="16x7 insulated", brand="Clopay", model="Gallery",
        material="steel", insulation_r=9.5, qty=3, has_windows=True,
        compare_at_price=900,
    )
    r = office.patch(f"/api/door-listings/{listing['id']}", json={"title": "16x7 insulated (dented)"})
    assert r.status_code == 200, r.text
    after = r.json()
    assert after["title"] == "16x7 insulated (dented)"
    assert after["brand"] == "Clopay"
    assert after["model"] == "Gallery"
    assert after["material"] == "steel"
    assert after["insulation_r"] == 9.5
    assert after["qty"] == 3
    assert after["has_windows"] is True
    assert after["compare_at_price"] == 900


