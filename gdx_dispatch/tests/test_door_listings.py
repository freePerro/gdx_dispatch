def _create(client: TestClient, **over) -> dict:
    body = {"title": "16x7 sandtone short panel", "listing_type": "used", "price": 450}
    body.update(over)
    r = client.post("/api/door-listings", json=body)
    assert r.status_code == 201, r.text
