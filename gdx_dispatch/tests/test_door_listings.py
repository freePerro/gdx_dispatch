# ── the customer-submission gate ─────────────────────────────────────────────


def _gate_db(company_on: bool, customer_on: bool):
    """Build the two gate rows through the ORM.

    Deliberately NOT raw SQL: SQLAlchemy's Uuid type stores a 32-char hex
    string on SQLite, so a hand-written INSERT of the dashed form silently
    fails to match on lookup — the row is there and the query still returns
    nothing.
    """
    engine = create_engine(
        "sqlite://", connect_args={"check_same_thread": False}, poolclass=StaticPool
    )
    TenantBase.metadata.create_all(engine, checkfirst=True)
    s = sessionmaker(bind=engine, autoflush=False, autocommit=False)()
    s.add(AppSettings(company_name="GDX", customer_listings_enabled=company_on))
    s.add(
        Customer(
            id=UUID(_CUSTOMER_ID),
            company_id=TENANT,
            name="Acme",
            can_submit_listings=customer_on,
        )
    )
    s.commit()
    return s


@pytest.mark.parametrize(
    ("company_on", "customer_on", "expected"),
    [
        (False, False, False),
        (False, True, False),   # company kill-switch beats a per-customer grant
        (True, False, False),   # per-customer defaults off
        (True, True, True),     # both required
    ],
)
def test_customer_gate_needs_both_switches(company_on, customer_on, expected):
    s = _gate_db(company_on, customer_on)
    try:
        assert service.customer_may_submit(s, _CUSTOMER_ID) is expected
    finally:
        s.close()


def test_customer_gate_is_off_with_no_settings_row():
    """Absent config must fail closed, not open."""
    engine = create_engine(
        "sqlite://", connect_args={"check_same_thread": False}, poolclass=StaticPool
    )
    TenantBase.metadata.create_all(engine, checkfirst=True)
    s = sessionmaker(bind=engine)()
    try:
        assert service.company_listings_enabled(s) is False
        assert service.customer_may_submit(s, _CUSTOMER_ID) is False
    finally:
        s.close()


