"""Door listings — the invariants that keep an unapproved door off the internet.

The feature's whole risk profile is that two semi-trusted sources (a tech in
the field, a customer in the portal) can create rows that a public website
renders. So these tests care much less about CRUD working and much more about:

  - a technician CANNOT publish (they hold inventory.write but not nav.office)
  - a submitter's row is FORCED to pending_review regardless of what they send
  - the public surfaces expose `published` rows ONLY
  - customer submission needs BOTH switches on, and defaults to off
"""
